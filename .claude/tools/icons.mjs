// Incremental icon generation: run after adding kinds or components (node icons.mjs [--force]).
// - writes icons/kinds/<kind>.svg for kinds that have a glyph but no icon
// - writes icons/components/<provider>/<id>.svg for components that have no icon
// Badge: badges-extra.json (id -> provider key) > providers.mjs COMPONENT_PROVIDER > provider-folder default.
//
// Every icon this script writes starts with the MARKER line below, and --force
// regenerates only files carrying it. An icon whose art came from somewhere else - an official
// vendor mark fitted by k8s-icons/convert.mjs, anything drawn by hand - has no marker and is never
// overwritten; --force prints what it left alone. --adopt-generated is the one-off migration for
// icons written before the marker existed: it stamps the marker onto files whose content is already
// byte-identical to what the generator would write today, and leaves every other file untouched.
// The marker sits before <svg>, where every consumer of these files already discards it: the
// bundle's `inner()`, design_to_svg.py and the web app's brandMarkFor() all slice from the opening
// <svg ...> tag. Provider marks under icons/providers/ are covered too: several of them were
// imported from simple-icons by hand rather than written by this script, and --force replaced one
// with its own wrapper before the marker existed.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as si from "simple-icons";
import { BOUNDARY_BRANDS, BOUNDARY_GLYPHS } from "./boundaries.mjs";
import { KIND_GLYPHS } from "./kindglyphs.mjs";
import { KIND_GLYPHS_EXTRA } from "./kindglyphs-extra.mjs";
import { pathIsValid } from "./pathcheck.mjs";
import { COMPONENT_PROVIDER, ORIGINAL_BADGES, PROVIDER_SLUG } from "./providers.mjs";
import { roundPath } from "./roundpath.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", ".."),
  ICONS = path.join(REPO, "icons");
const GLYPHS = { ...KIND_GLYPHS, ...KIND_GLYPHS_EXTRA };
const EXTRA = JSON.parse(fs.readFileSync(new URL("./badges-extra.json", import.meta.url), "utf8"));
const FORCE = process.argv.includes("--force");
const ADOPT = process.argv.includes("--adopt-generated");
const bySlug = {};
for (const k of Object.keys(si)) {
  const i = si[k];
  if (i && i.slug) bySlug[i.slug] = i;
}
const OPEN =
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">';
// The glyph repeats its presentation attributes on an inner <g> as well as on the root, so a
// consumer that inlines the body (a renderer, a sprite sheet) keeps the stroke.
const INNER =
  '<g fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">';
const MARKER = "<!-- generated by icons.mjs -->";
const body = (b) => `${OPEN}${INNER}${b}</g></svg>
`;
const kindSvg = (b) => `${MARKER}
${body(b)}`;
const adopted = [],
  protectedFiles = [];
/**
 * Write one generated icon; `text` is the file including its marker line. Returns true when the
 * file changed on disk.
 *
 * Without --force an existing file is left alone, as before. With --force the marker decides: a
 * file the generator wrote is rewritten, a file it did not write is recorded and kept. Under
 * --adopt-generated nothing is regenerated; a marker-less file whose bytes already match today's
 * output gains the marker and nothing else does.
 */
const put = (out, text) => {
  const bare = text.slice(MARKER.length + 1);
  if (!fs.existsSync(out)) {
    if (ADOPT) return false;
    fs.writeFileSync(out, text);
    return true;
  }
  const current = fs.readFileSync(out, "utf8");
  const marked = current.startsWith(MARKER);
  if (ADOPT) {
    if (marked) return false;
    if (current !== bare) return false;
    fs.writeFileSync(out, text);
    adopted.push(path.relative(ICONS, out).split(path.sep).join("/"));
    return true;
  }
  if (!FORCE) return false;
  if (!marked) {
    protectedFiles.push(path.relative(ICONS, out).split(path.sep).join("/"));
    return false;
  }
  if (current === text) return false;
  fs.writeFileSync(out, text);
  return true;
};
// Round every number in a path. A number that shortens must not merge with the one before it:
// the source relies on '.' or '-' as an implicit separator, and a value that rounds to "0"
// loses that separator, which turns two coordinates into one and makes the path invalid.
// Shorten a mark to fit the budget, but never at the cost of correctness: a rounding that
// merges two coordinates into one is discarded, and the unrounded path is used instead.
const fitPath = (d) => {
  for (const n of [3, 2, 1, 0]) {
    const r = roundPath(d, n);
    if (r && r.length <= 2996 && pathIsValid(r)) return r;
  }
  return d.length <= 2996 && pathIsValid(d) ? d : null;
};
const ORIG = {
  ...ORIGINAL_BADGES,
  oci: {
    hex: "C74634",
    title: "OCI (original neutral mark)",
    path: "M7 5h10a7 7 0 0 1 0 14H7A7 7 0 0 1 7 5zm0 3a4 4 0 0 0 0 8h10a4 4 0 0 0 0-8z",
  },
};
const SLUGS = { ...PROVIDER_SLUG, oci: null };
const providerInfo = {};
for (const [key, slug] of Object.entries(SLUGS)) {
  if (slug === null) {
    const o = ORIG[key];
    if (o) providerInfo[key] = { ...o, source: "original" };
    continue;
  }
  const icon = bySlug[slug];
  if (!icon) continue;
  const d = fitPath(icon.path);
  if (!d) continue;
  providerInfo[key] = { hex: icon.hex, path: d, title: icon.title, source: "simple-icons" };
}
// any badge key named in badges-extra.json that is a simple-icons slug not yet in providers.mjs
for (const key of new Set(Object.values(EXTRA)))
  if (!providerInfo[key] && bySlug[key]) {
    const d = fitPath(bySlug[key].path);
    if (d)
      providerInfo[key] = {
        hex: bySlug[key].hex,
        path: d,
        title: bySlug[key].title,
        source: "simple-icons",
      };
  }
for (const [key, p] of Object.entries(providerInfo)) {
  const f = path.join(ICONS, "providers", `${key}.svg`);
  if (fs.existsSync(f) && !FORCE && !ADOPT) continue;
  put(
    f,
    `${MARKER}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" role="img" fill="#${p.hex}"><title>${p.title.replace(/&/g, "&amp;").replace(/</g, "&lt;")}</title><g fill="#${p.hex}"><path${p.source === "original" ? ' fill-rule="evenodd"' : ""} d="${p.path}"/></g></svg>\n`,
  );
}
// Boundary icons (icons/boundaries/<id>.svg): a mark or a concept glyph a boundary can show
// before its label. A brand mark is copied from icons/providers/<key>.svg when there is one and
// fitted from Simple Icons otherwise. Unlike a provider file it carries no <title> (the name is in
// locales/en.yaml) and its <g> says stroke="none", because the renderer draws it inside a context
// that strokes with currentColor. A near-black mark (GitHub, Anthropic, Apple) is drawn in
// currentColor instead, so it follows the theme rather than vanishing on a dark canvas.
const luminance = (hex) => {
  const c = (n) => {
    const v = parseInt(hex.substr(n, 2), 16) / 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * c(0) + 0.7152 * c(2) + 0.0722 * c(4);
};
const boundaryMark = (key) => {
  const f = path.join(ICONS, "providers", `${key}.svg`);
  if (fs.existsSync(f)) {
    const raw = fs.readFileSync(f, "utf8");
    const hex = /<g fill="#([0-9A-Fa-f]{6})"/.exec(raw)?.[1];
    const paths = [...raw.matchAll(/<path( fill-rule="evenodd")? d="([^"]+)"\/>/g)];
    if (hex && paths.length === 1)
      return { hex, path: paths[0][2], evenodd: Boolean(paths[0][1]), source: "providers" };
  }
  const icon = bySlug[key];
  const d = icon ? fitPath(icon.path) : null;
  return d ? { hex: icon.hex, path: d, evenodd: false, source: "simple-icons" } : null;
};
fs.mkdirSync(path.join(ICONS, "boundaries"), { recursive: true });
let bn = 0;
const noMark = [],
  themed = [];
for (const [id, key] of Object.entries(BOUNDARY_BRANDS)) {
  const m = boundaryMark(key);
  if (!m) {
    noMark.push(`${id} (${key})`);
    continue;
  }
  const fill = luminance(m.hex) < 0.03 ? "currentColor" : `#${m.hex}`;
  if (fill === "currentColor") themed.push(id);
  const text = `${MARKER}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="${fill}"><g fill="${fill}" stroke="none"><path${m.evenodd ? ' fill-rule="evenodd"' : ""} d="${m.path}"/></g></svg>
`;
  if (put(path.join(ICONS, "boundaries", `${id}.svg`), text)) bn++;
}
for (const [id, glyph] of Object.entries(BOUNDARY_GLYPHS)) {
  if (BOUNDARY_BRANDS[id]) noMark.push(`${id} (both a brand and a glyph)`);
  else if (put(path.join(ICONS, "boundaries", `${id}.svg`), kindSvg(glyph))) bn++;
}
if (!ADOPT) console.log(`boundary icons written: ${bn}${themed.length ? ` (in currentColor: ${themed.join(" ")})` : ""}`);
if (noMark.length) {
  console.log("BOUNDARY ICON WITHOUT A MARK:", noMark.join(", "));
  process.exitCode = 1;
}
const CX = 18.5,
  CY = 18.5,
  R = 4.5,
  HALO = 5.3,
  MARK = 5.4,
  S = (MARK / 24).toFixed(4),
  TX = (CX - MARK / 2).toFixed(2),
  TY = (CY - MARK / 2).toFixed(2);
const markColour = (hex) => {
  const c = (n) => {
    const v = parseInt(hex.substr(n, 2), 16) / 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * c(0) + 0.7152 * c(2) + 0.0722 * c(4) > 0.45 ? "#111" : "#fff";
};
const badge = (p) =>
  `<g stroke="none"><circle cx="${CX}" cy="${CY}" r="${HALO}" fill="var(--zeema-icon-bg, #fff)"/><circle cx="${CX}" cy="${CY}" r="${R}" fill="#${p.hex}"/><path transform="translate(${TX} ${TY}) scale(${S})" fill="${markColour(p.hex)}"${p.source === "original" ? ' fill-rule="evenodd"' : ""} d="${p.path}"/></g>`;
const DEFAULT_BADGE = {
  aws: "aws",
  azure: "azure",
  gcp: "googlecloud",
  cloudflare: "cloudflare",
  oci: "oci",
  ibm: "ibm",
  alibabacloud: "alibabacloud",
  digitalocean: "digitalocean",
  openstack: "openstack",
  outscale: "outscale",
  k8s: "kubernetes",
  default: null,
};
let kn = 0,
  cn = 0;
const missingGlyph = [],
  noBadge = [];
for (const f of fs.readdirSync(path.join(REPO, "kinds")).filter((f) => f.endsWith(".yaml"))) {
  const k = f.slice(0, -5),
    out = path.join(ICONS, "kinds", `${k}.svg`);
  if (!GLYPHS[k]) {
    missingGlyph.push(k);
    continue;
  }
  if (put(out, kindSvg(GLYPHS[k]))) kn++;
}
for (const prov of fs.readdirSync(path.join(REPO, "components"))) {
  const dir = path.join(REPO, "components", prov);
  if (!fs.statSync(dir).isDirectory()) continue;
  fs.mkdirSync(path.join(ICONS, "components", prov), { recursive: true });
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".yaml"))) {
    const src = fs.readFileSync(path.join(dir, f), "utf8");
    const id = /^id:\s*"?([^"\n]+)"?/m.exec(src)[1].trim(),
      kind = /^kind:\s*"?([^"\n]+)"?/m.exec(src)[1].trim();
    const out = path.join(ICONS, "components", prov, `${id}.svg`);
    if (fs.existsSync(out) && !FORCE && !ADOPT) continue;
    const glyph = GLYPHS[kind];
    if (!glyph) {
      missingGlyph.push(`${kind} (for ${id})`);
      continue;
    }
    const key = EXTRA[id] ?? COMPONENT_PROVIDER[id] ?? DEFAULT_BADGE[prov];
    const p = key ? providerInfo[key] : null;
    if (!p) noBadge.push(id);
    if (put(out, kindSvg(p ? glyph + badge(p) : glyph))) cn++;
  }
}
if (ADOPT) {
  console.log(`marker added to ${adopted.length} icon${adopted.length === 1 ? "" : "s"} already identical to the generator's output`);
} else {
  console.log(`kind icons written: ${kn}, component icons written: ${cn}`);
}
if (protectedFiles.length) {
  console.log(
    `--force left ${protectedFiles.length} icon${protectedFiles.length === 1 ? "" : "s"} alone (no "${MARKER}" marker, so not ours to rewrite):`,
  );
  for (const f of protectedFiles.slice(0, 20)) console.log(`  ${f}`);
  if (protectedFiles.length > 20) console.log(`  ... and ${protectedFiles.length - 20} more`);
}
if (missingGlyph.length) {
  console.log("MISSING GLYPH:", [...new Set(missingGlyph)].join(", "));
  process.exitCode = 1;
}
if (noBadge.length) console.log("written without badge:", noBadge.join(" "));
